"""Validate JSON, generate C++ function cards, and register them in the catalog.

Only Python's standard library is required. Runtime never executes JSON as code.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MARKER = '// Generated by tools/import_function_card.py. DO NOT EDIT.\n'
MAX_AMOUNT = (1 << 63) - 1
MAX_ID = (1 << 53) - 1  # Exact in the browser's JSON number representation.
RESERVED_IDS = {*range(1, 11), 1001, 1002, 1003, 1004, 900001, 900002, 900003}
RESERVED_KEYS = {'con','prn','aux','nul',*(f'com{i}' for i in range(1,10)),*(f'lpt{i}' for i in range(1,10))}
# event: (concrete class, subject field or None, allowed settlement kind).
EVENTS = {
    'PlayCommitted': ('CardsPlayedEvent', 'player', 'fact'),
    'PassCommitted': ('PlayerPassedEvent', 'player', 'fact'),
    'ShopEnter': ('ShopEnteredEvent', 'player', 'fact'),
    'ShopLeave': ('ShopLeftEvent', 'player', 'fact'),
    'TurnStart': ('TurnStartedEvent', 'player', 'fact'),
    'TurnEnd': ('TurnEndedEvent', 'player', 'fact'),
    'DrawAfter': ('CardsDrawnEvent', 'player', 'fact'),
    'RoundStart': ('RoundStartedEvent', None, 'fact'),
    'RoundEnd': ('RoundEndedEvent', None, 'fact'),
    'TrickStart': ('TrickStartedEvent', None, 'fact'),
    'TrickEnd': ('TrickEndedEvent', None, 'fact'),
    'GameEnd': ('GameEndedEvent', None, 'fact'),
    'PlayRewardBefore': ('BeforePlayRewardEvent', 'player', 'reward'),
    'RoundRewardBefore': ('BeforeRoundRewardEvent', 'player', 'reward'),
    'ShopBuyQuote': ('BeforeShopPurchaseEvent', 'player', 'shop'),
    'ShopRefreshQuote': ('BeforeShopRefreshEvent', 'player', 'shop'),
}
ACTIONS = {
    'add_score': 'fact', 'gain_coins': 'fact',
    'add_pending_score': 'reward', 'add_pending_coins': 'reward',
    'reduce_shop_cost': 'shop',
}
SCORE_ACTIONS = {'add_score', 'add_pending_score'}
COIN_ACTIONS = {'gain_coins', 'add_pending_coins'}


class CardError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise CardError(message)


def object_keys(value, required, optional, where):
    require(type(value) is dict, f'{where}: expected an object')
    require(required <= value.keys(), f'{where}: missing fields {sorted(required-value.keys())}')
    require(not (value.keys()-required-optional), f'{where}: unknown fields {sorted(value.keys()-required-optional)}')


def integer(value, minimum, maximum, where):
    require(type(value) is int and minimum <= value <= maximum,
            f'{where}: expected integer {minimum}..{maximum}')


def text(value, maximum, where):
    require(type(value) is str and bool(value.strip()) and len(value) <= maximum,
            f'{where}: expected non-empty text, at most {maximum} characters')
    require(not any(ord(c) < 32 or ord(c) == 127 for c in value), f'{where}: control characters are not allowed')
    try:
        value.encode('utf-8')
    except UnicodeError as e:
        raise CardError(f'{where}: invalid Unicode') from e


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, f'duplicate JSON field: {key}')
        result[key] = value
    return result


def load_card(path):
    try:
        require(path.stat().st_size <= 256*1024, f'{path}: JSON exceeds 256 KiB')
        raw = json.loads(path.read_text(encoding='utf-8-sig'), object_pairs_hook=unique_object)
    except (OSError, UnicodeError, json.JSONDecodeError, RecursionError) as e:
        raise CardError(f'{path}: {e}') from e
    return validate(raw)


def validate(card):
    object_keys(card, {'version','type','id','key','name','price','description','abilities'}, {'minimum_shop_level'}, 'card')
    integer(card['version'], 1, 1, 'version')
    require(card['type'] == 'function', 'type: only function cards are supported')
    integer(card['id'], 1, MAX_ID, 'id')
    require(card['id'] not in RESERVED_IDS, 'id: conflicts with a built-in card or consumable')
    require(type(card['key']) is str and len(card['key']) <= 64 and
            re.fullmatch(r'[a-z][a-z0-9]*(?:_[a-z0-9]+)*', card['key']),
            'key: use lowercase ASCII letters, digits and single underscores')
    require(card['key'] not in RESERVED_KEYS, 'key: reserved Windows device filename')
    text(card['name'], 128, 'name'); text(card['description'], 2048, 'description')
    integer(card['price'], 0, MAX_AMOUNT, 'price')
    integer(card.get('minimum_shop_level', 1), 1, 3, 'minimum_shop_level')
    require(type(card['abilities']) is list and 1 <= len(card['abilities']) <= 64, 'abilities: expected 1..64 atomic abilities')
    for i, skill in enumerate(card['abilities']):
        at = f'abilities[{i}]'
        object_keys(skill, {'event','op','amount'}, {'scope','minimum'}, at)
        require(type(skill['event']) is str and skill['event'] in EVENTS, f'{at}.event: unsupported event')
        scope = skill.get('scope', 'self')
        require(scope in ('self','any_player'), f'{at}.scope: use self or any_player')
        _, subject, kind = EVENTS[skill['event']]
        require(subject is not None or scope == 'self', f'{at}: global events use scope self')
        op = skill['op']
        require(type(op) is str and op in ACTIONS, f'{at}.op: unsupported atomic action')
        require(ACTIONS[op] == kind, f'{at}: action {op} cannot run at event {skill["event"]}')
        integer(skill['amount'], 1, MAX_AMOUNT, at+'.amount')
        if 'minimum' in skill:
            require(op == 'reduce_shop_cost', f'{at}: minimum is only valid for reduce_shop_cost')
            integer(skill['minimum'], 0, MAX_AMOUNT, at+'.minimum')
    # Normalize defaults so importing an unchanged definition is deterministic.
    result = json.loads(json.dumps(card))
    result.setdefault('minimum_shop_level', 1)
    for skill in result['abilities']:
        skill.setdefault('scope', 'self')
        if skill['op'] == 'reduce_shop_cost': skill.setdefault('minimum', 0)
    return result


def cpp(value):
    return json.dumps(value, ensure_ascii=False)


def render(card):
    key = card['key']; cls = 'JsonCard_'+key
    header = MARKER + f'// Card identity: {key} {card["id"]}\n' + f'''#pragma once
#include "FunctionCards.hpp"
#include "Player.hpp"
namespace cardgame::generated {{
class {cls} final : public FunctionCards {{
public:
    {cls}(Player& owner, std::size_t sequence);
    void resolve(const Context& context, CardEffects& effects) override;
    std::string description() const override;
protected:
    void validate_bonus_upgrade(ScoreValue score, CoinValue coins) const override;
    void apply_bonus_upgrade(ScoreValue score, CoinValue coins) noexcept override;
private:
    Player& owner_;
    ScoreValue scoreBonus_ = 0;
    CoinValue coinBonus_ = 0;
}};
CardPtr make_{key}(Player& owner, std::size_t sequence);
}} // namespace cardgame::generated
'''
    triggers = ', '.join('EventType::'+x for x in sorted({s['event'] for s in card['abilities']}))
    # Numeric enhancement applies to each corresponding score/coin action.
    amounts = {False: [], True: []}
    parts = [MARKER, f'''#include "cards/generated/{key}.hpp"
#include "Abilities.hpp"
#include "HandleEvent.hpp"
#include <limits>
#include <stdexcept>
namespace cardgame::generated {{
{cls}::{cls}(Player& owner, std::size_t sequence)
    : FunctionCards(CardRef{{owner.id,sequence}}, {card['id']}ULL, {cpp(card['name'])},
                    listens_to({{{triggers}}}), true), owner_(owner) {{}}
void {cls}::resolve(const Context& c, CardEffects& out) {{
''']
    for index, skill in enumerate(card['abilities'], 1):
        event_class, subject, kind = EVENTS[skill['event']]
        parts.append(f'    if (c.type()==EventType::{skill["event"]}) {{\n')
        if subject and skill['scope'] == 'self':
            parts.append(f'        const auto* event=c.event_as<{event_class}>();\n'
                         f'        if (event && event->{subject}==owner_.id) {{\n')
        else:
            parts.append('        {\n')
        if kind == 'fact':
            parts.append('            if(c.metadata()->mode!=ExecutionMode::Preview) {\n')
        op = skill['op']; value = str(skill['amount'])+'LL'
        if op in SCORE_ACTIONS:
            amounts[False].append(skill['amount']); value += '+scoreBonus_'
        if op in COIN_ACTIONS:
            amounts[True].append(skill['amount']); value += '+coinBonus_'
        expressions = {
            'add_score': f'out.emit(abilities::add_score(owner_,{value}),{index})',
            'gain_coins': f'out.emit(abilities::gain_coins(owner_,{value},"JSON function card"),{index})',
            'add_pending_score': f'abilities::add_pending_score(out.reward(),{value})',
            'add_pending_coins': f'abilities::add_pending_coins(out.reward().coins,{value})',
            'reduce_shop_cost': f'abilities::reduce_shop_cost(out.shop(),{value},{skill.get("minimum",0)}LL)',
        }
        parts.append('            '+expressions[op]+';\n')
        if kind == 'fact': parts.append('            }\n')
        parts.append('        }\n    }\n')
    parts.append(f'''}}
std::string {cls}::description() const {{
    std::string text={cpp(card['description'])};
    if(scoreBonus_)text+=" [score bonus +"+std::to_string(scoreBonus_)+"]";
    if(coinBonus_)text+=" [coin bonus +"+std::to_string(coinBonus_)+"]";
    return text;
}}
void {cls}::validate_bonus_upgrade(ScoreValue score, CoinValue coins) const {{
''')
    for is_coin, values in amounts.items():
        arg, field = ('coins','coinBonus_') if is_coin else ('score','scoreBonus_')
        if values:
            limit = MAX_AMOUNT-max(values)
            parts.append(f'    if({arg}>{limit}LL-{field})throw std::overflow_error("JSON card bonus overflow");\n')
        else:
            parts.append(f'    if({arg})throw std::invalid_argument("JSON card has no {arg} action");\n')
    parts.append(f'''}}
void {cls}::apply_bonus_upgrade(ScoreValue score, CoinValue coins) noexcept {{
    scoreBonus_+=score;coinBonus_+=coins;
}}
CardPtr make_{key}(Player& owner, std::size_t sequence) {{
    return std::make_shared<{cls}>(owner,sequence);
}}
}} // namespace cardgame::generated
''')
    return header, ''.join(parts)


def render_catalog(cards):
    includes = ''.join(f'#include "cards/generated/{c["key"]}.hpp"\n' for c in cards)
    lines = [MARKER, '#include "CardCatalog.hpp"\n', includes,
             'namespace cardgame {\nstd::vector<SchedulerConfig::CardDefinition> generated_function_cards() {\n    return {\n']
    for c in cards:
        lines.append(f'        {{{c["id"]}ULL,{cpp(c["name"])},{c["price"]}LL,generated::make_{c["key"]},{c["minimum_shop_level"]},{cpp(c["description"])}}},\n')
    lines.append('    };\n}\n} // namespace cardgame\n')
    return ''.join(lines)


def safe_path(root, relative):
    path = root / relative
    require(path.resolve().is_relative_to(root), f'output escapes project root: {relative}')
    return path


def commit_outputs(outputs):
    """Prepare every file first; replace atomically per file and restore on error."""
    previous = {p: p.read_bytes() if p.exists() else None for p in outputs}
    pending = {}; applied = []
    try:
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=path.parent, prefix='.card-import-', delete=False) as f:
                pending[path] = Path(f.name)
                f.write(content)
        for path, temp in pending.items():
            os.replace(temp, path); applied.append(path)
    except BaseException:
        for path in reversed(applied):
            if previous[path] is None: path.unlink()
            else: path.write_bytes(previous[path])
        raise
    finally:
        for temp in pending.values():
            if temp.exists(): temp.unlink()


def import_card(source, root=ROOT, force=False, check=False):
    root = root.resolve()
    incoming = load_card(source)
    cards = {}
    directory = safe_path(root, 'cards/function')
    for path in sorted(directory.glob('*.json')):
        card = load_card(path)
        require(path.stem == card['key'], f'{path}: filename must equal key')
        require(card['key'] not in cards, 'duplicate card key')
        cards[card['key']] = card
    key = incoming['key']
    if key in cards and cards[key] != incoming:
        require(force, 'card already exists with different JSON; use --force to update')
        require(cards[key]['id'] == incoming['id'], 'cannot change an existing card ID')
    cards[key] = incoming
    definitions = sorted(cards.values(), key=lambda c: c['key'])
    ids = [card['id'] for card in definitions]
    require(len(ids) == len(set(ids)), 'duplicate card ID in JSON catalog')
    outputs = {}
    for card in definitions:
        header, source_cpp = render(card)
        for relative, content in [(f'include/cards/generated/{card["key"]}.hpp', header),
                                  (f'src/cards/generated/{card["key"]}.cpp', source_cpp)]:
            path = safe_path(root, relative)
            if path.exists():
                existing = path.read_text(encoding='utf-8')
                require(existing.startswith(MARKER), f'refusing to overwrite hand-written file: {path}')
                if path.suffix == '.hpp':
                    identity = re.search(r'^// Card identity: (\S+) (\d+)$', existing, re.MULTILINE)
                    require(identity is not None and identity.groups() == (card['key'],str(card['id'])),
                            'cannot change the identity of an existing generated card')
                require(existing == content or force, f'generated card changed; use --force: {path.name}')
            outputs[path] = content.encode('utf-8')
    catalog = safe_path(root, 'src/CardCatalog.cpp')
    if catalog.exists(): require(catalog.read_text(encoding='utf-8').startswith(MARKER), 'refusing to overwrite hand-written CardCatalog.cpp')
    outputs[catalog] = render_catalog(definitions).encode('utf-8')
    canonical = safe_path(root, f'cards/function/{key}.json')
    outputs[canonical] = (json.dumps(incoming, ensure_ascii=False, indent=2)+'\n').encode('utf-8')
    changed = {p: b for p,b in outputs.items() if not p.exists() or p.read_bytes() != b}
    if not check: commit_outputs(changed)
    return [str(p.relative_to(root)).replace('\\','/') for p in changed]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('json_file', type=Path)
    parser.add_argument('--check', action='store_true', help='validate and list changes without writing')
    parser.add_argument('--force', action='store_true', help='update existing generated cards, preserving their IDs')
    args = parser.parse_args()
    try:
        changed = import_card(args.json_file, force=args.force, check=args.check)
    except (CardError,OSError) as e:
        print(f'Import failed: {e}', file=sys.stderr); return 1
    print(('Validated (no files written)' if args.check else 'Imported')+f': {len(changed)} file(s)')
    for path in changed: print('  '+path)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
